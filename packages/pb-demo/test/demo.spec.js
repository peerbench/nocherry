import { test, expect } from '@playwright/test';

test.describe('Demo webapp browser tests', () => {
  test('Home page loads', async ({ page }) => {
    await page.goto('/');
    // The hero section has an h1 with this text
    await expect(page.locator('.hero h1')).toContainText('Commit-Reveal Protocol');
    await expect(page.locator('button', { hasText: 'Start Demo' })).toBeVisible();
  });

  test('Full 7-step walkthrough', async ({ page }) => {
    // Navigate to home and click "Start Demo"
    // The "Start Demo" form POSTs to /steps/1, which generates a keypair
    // and redirects back to GET /steps/1 (with keypair in session).
    // So we go directly from home to step 1 with keypair already generated.
    await page.goto('/');
    await page.locator('button', { hasText: 'Start Demo' }).click();
    await page.waitForURL('**/steps/1');

    // Step 1: Keypair already generated by "Start Demo" click
    // Assert did:key is visible in the content panel (not in code refs)
    await expect(page.locator('.content-panel .field-value', { hasText: 'did:key:z' })).toBeVisible();
    await page.locator('a', { hasText: 'Continue to Step 2' }).click();
    await page.waitForURL('**/steps/2');

    // Step 2: Generate & Hash random data
    await page.locator('button', { hasText: 'Generate & Hash' }).click();
    await page.waitForURL('**/steps/2');
    // Assert SHA-256 hashes are visible (field labels in content panel)
    await expect(page.locator('.content-panel .field-label', { hasText: 'SHA-256' }).first()).toBeVisible();
    await page.locator('a', { hasText: 'Continue to Step 3' }).click();
    await page.waitForURL('**/steps/3');

    // Step 3: Create & Sign Commitment
    await page.locator('button', { hasText: /Create.*Sign Commitment/ }).click();
    await page.waitForURL('**/steps/3');
    // Assert commitment_hash visible in the content panel
    await expect(page.locator('.content-panel .field-label', { hasText: 'Commitment Hash' })).toBeVisible();
    await page.locator('a', { hasText: 'Continue to Step 4' }).click();
    await page.waitForURL('**/steps/4');

    // Step 4: Submit to Server (JS-driven, no page reload)
    // Wait for the beacon ticker to appear (confirms JS is running)
    await expect(page.locator('.beacon-ticker')).toBeVisible({ timeout: 10_000 });
    await page.locator('#submit-btn').click();
    // Wait for the receipt to render in #receipt-result (may take up to 15s for drand beacon)
    await expect(page.locator('#receipt-result', { hasText: '201 Created' })).toBeVisible({ timeout: 30_000 });
    await page.locator('a', { hasText: 'Continue to Step 5' }).click();
    await page.waitForURL('**/steps/5');

    // Step 5: Selection Result
    await expect(page.locator('.content-panel h2', { hasText: 'Selection Result' })).toBeVisible();
    // Verify drand round info is visible
    await expect(page.locator('.content-panel .field-label', { hasText: 'Selection Round' })).toBeVisible();
    await page.locator('a', { hasText: 'Continue to Step 6' }).click();
    await page.waitForURL('**/steps/6');

    // Step 6: Create & Submit Reveal
    await page.locator('button', { hasText: /Create.*Submit Reveal/ }).click();
    await page.waitForURL('**/steps/6');
    // Assert reveal info visible
    await expect(page.locator('.content-panel .field-label', { hasText: 'Reveal ID' })).toBeVisible();
    await page.locator('a', { hasText: 'Continue to Step 7' }).click();
    await page.waitForURL('**/steps/7');

    // Step 7: Run Verification
    await page.locator('button', { hasText: 'Run Verification' }).click();
    await page.waitForURL('**/steps/7');
    await expect(page.locator('.content-panel', { hasText: 'All checks passed' })).toBeVisible();
  });

  test('Step navigation shows progress', async ({ page }) => {
    // Start fresh: "Start Demo" generates keypair (completes step 1)
    // and lands on GET /steps/1 showing the keypair.
    await page.goto('/');
    await page.locator('button', { hasText: 'Start Demo' }).click();
    await page.waitForURL('**/steps/1');

    // After completing step 1, navigate to step 2 to see progress nav
    await page.locator('a', { hasText: 'Continue to Step 2' }).click();
    await page.waitForURL('**/steps/2');

    // Step 1 should have "done" class in the nav
    const step1Div = page.locator('.steps-nav .step').first();
    await expect(step1Div).toHaveClass(/done/);

    // Step 2 should be current
    const step2Div = page.locator('.steps-nav .step').nth(1);
    await expect(step2Div).toHaveClass(/current/);
  });

  test('Direct URL access to incomplete step redirects', async ({ page }) => {
    // Use a fresh browser context (no session), navigate to step 5
    await page.goto('/steps/5');

    // Should redirect to an earlier step since the session has no data
    // Step 5 checks session.receipt -> redirects to /steps/4
    // Step 4 checks session.commitment -> redirects to /steps/3
    // Step 3 checks session.itemHashes -> redirects to /steps/2
    // Step 2 checks session.keypair -> redirects to /steps/1
    const url = page.url();
    expect(url).not.toContain('/steps/5');
    // Should end up at an earlier step (likely /steps/1 since no session data)
    expect(url).toMatch(/\/steps\/[1-4]/);
  });
});
