#!/usr/bin/env node
/**
 * Regenerate the WASM glue vendored by every deployment target from the
 * pb-wasm crate, so that no target is left with an export list that predates
 * the core.
 *
 *   node deploy/scripts/regen-wasm.mjs            build and rewrite all targets
 *   node deploy/scripts/regen-wasm.mjs --check    exit 1 if any target is stale
 *
 * Targets and how each one loads WASM:
 *   deploy/cloudflare/src/wasm                ESM glue, `import wasmModule from './pb_wasm_bg.wasm'`
 *                                              (the .wasm itself is copied by deploy.js and gitignored)
 *   deploy/cloudflare-demo/src/wasm           same as cloudflare, .wasm vendored
 *   dev-reveal-publishing-helpers/cloudflare-r2/src/wasm   same as cloudflare, .wasm vendored
 *   deploy/google-cloud/src/wasm              ESM glue, fs.readFileSync of the vendored .wasm
 *   deploy/supabase/.../commit-reveal/wasm    wasm-pack --target web glue, .wasm vendored and
 *                                              inlined as base64 in pb_wasm_bg.ts, export list in mod.ts
 *
 * Servers never verify BLS beacon signatures, so every target is built with
 * `--no-default-features` (about 300 KB instead of 750 KB). The nodejs build
 * for the SDK (`npm run build:wasm`) is not touched.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CRATE = join(ROOT, 'packages', 'pb-wasm');

const CF_HEADER = `/* @ts-self-types="./pb_wasm.d.ts" */
/**
 * ESM WASM glue for Cloudflare Workers.
 * Transformed from the CJS pkg/pb_wasm.js - replaces Node.js fs loading
 * with ESM static import of compiled WASM module.
 * Generated by deploy/scripts/regen-wasm.mjs; do not edit by hand.
 */

import wasmModule from './pb_wasm_bg.wasm';
`;

const GC_HEADER = `/* @ts-self-types="./pb_wasm.d.ts" */
/**
 * ESM WASM glue for Node.js (Cloud Run).
 * Transformed from the CJS pkg/pb_wasm.js - replaces Cloudflare Workers
 * static WASM import with Node.js fs.readFileSync + WebAssembly.Module.
 * Generated by deploy/scripts/regen-wasm.mjs; do not edit by hand.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const wasmBytes = readFileSync(join(__dirname, 'pb_wasm_bg.wasm'));
const wasmModule = new WebAssembly.Module(wasmBytes);
`;

const ESM_TAIL = `
// ESM WASM instantiation
const wasm = new WebAssembly.Instance(wasmModule, __wbg_get_imports()).exports;
wasm.__wbindgen_start();
`;

const ESM_TARGETS = [
  { dir: 'deploy/cloudflare/src/wasm', header: CF_HEADER, vendorWasm: false },
  { dir: 'deploy/cloudflare-demo/src/wasm', header: CF_HEADER, vendorWasm: true },
  { dir: 'dev-reveal-publishing-helpers/cloudflare-r2/src/wasm', header: CF_HEADER, vendorWasm: true },
  { dir: 'deploy/google-cloud/src/wasm', header: GC_HEADER, vendorWasm: true },
];
const SUPABASE_DIR = 'deploy/supabase/supabase/functions/commit-reveal/wasm';

function wasmPack(target, outDir) {
  execFileSync('wasm-pack', ['build', CRATE, '--release', '--target', target, '--out-dir', outDir, '--scope', 'nocherry', '--', '--no-default-features'],
    { stdio: 'inherit' });
}

/** Exported function names of a wasm-bindgen .d.ts, sorted. */
function exportsOf(dts) {
  return [...dts.matchAll(/^export function (\w+)\(/gm)].map((m) => m[1]).sort();
}

/**
 * CJS (`--target nodejs`) glue to ESM: `function X` that is exported becomes
 * `export function X`, the `exports.X = X` lines go, and the Node loader at the
 * end is replaced by `tail`. Everything else is left exactly as generated.
 */
function cjsToEsm(cjs, header, tail) {
  const exported = new Set([...cjs.matchAll(/^(?:module\.)?exports\.(\w+) = \1;$/gm)].map((m) => m[1]));
  let body = cjs
    .replace(/^\/\* @ts-self-types=.*\*\/\n/, '')
    .replace(/^(?:module\.)?exports\.\w+ = \w+;\n/gm, '')
    .replace(/^function (\w+)\(/gm, (line, name) => (exported.has(name) ? `export function ${name}(` : line));
  const loaderStart = body.indexOf('\nconst wasmPath = ');
  if (loaderStart < 0) throw new Error('did not find the Node.js loader at the end of pkg/pb_wasm.js; wasm-bindgen output changed');
  body = body.slice(0, loaderStart);
  return header + '\n' + body.replace(/^\n+/, '') + tail;
}

/** Supabase: base64 of the .wasm and the export list of mod.ts. */
function supabaseFiles(wasmBytes, dts, existingMod) {
  const base64 = `export const WASM_BASE64 = \`${wasmBytes.toString('base64')}\`;\n`;
  const names = exportsOf(dts).filter((n) => n !== 'default' && n !== 'initSync');
  const marker = '// Re-export all WASM functions\n';
  const head = existingMod.includes(marker) ? existingMod.slice(0, existingMod.indexOf(marker)) : existingMod;
  const mod = head + marker + names.map((n) => `export const ${n} = wasmExports.${n};`).join('\n') + '\n';
  return { base64, mod };
}

function main() {
  const check = process.argv.includes('--check');
  const tmp = mkdtempSync(join(tmpdir(), 'pb-wasm-regen-'));
  const nodejsOut = join(tmp, 'nodejs');
  const webOut = join(tmp, 'web');
  wasmPack('nodejs', nodejsOut);
  wasmPack('web', webOut);

  const cjs = readFileSync(join(nodejsOut, 'pb_wasm.js'), 'utf-8');
  const dts = readFileSync(join(nodejsOut, 'pb_wasm.d.ts'), 'utf-8');
  const wasmBytes = readFileSync(join(nodejsOut, 'pb_wasm_bg.wasm'));
  const wantExports = exportsOf(dts);
  let stale = 0;

  const write = (path, content) => {
    const abs = join(ROOT, path);
    const current = existsSync(abs) ? readFileSync(abs) : null;
    const same = current !== null && Buffer.compare(current, Buffer.isBuffer(content) ? content : Buffer.from(content)) === 0;
    if (same) return;
    stale++;
    if (check) { console.log(`stale: ${path}`); return; }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote: ${path}`);
  };

  for (const t of ESM_TARGETS) {
    const glue = cjsToEsm(cjs, t.header, ESM_TAIL);
    const have = exportsOf(glue);
    if (have.join() !== wantExports.join()) throw new Error(`${t.dir}: transformed glue exports ${have.length} functions, core has ${wantExports.length}`);
    write(join(t.dir, 'pb_wasm.js'), glue);
    write(join(t.dir, 'pb_wasm.d.ts'), dts);
    if (t.vendorWasm) write(join(t.dir, 'pb_wasm_bg.wasm'), wasmBytes);
  }

  const webDts = readFileSync(join(webOut, 'pb_wasm.d.ts'), 'utf-8');
  const webWasm = readFileSync(join(webOut, 'pb_wasm_bg.wasm'));
  const modPath = join(ROOT, SUPABASE_DIR, 'mod.ts');
  const { base64, mod } = supabaseFiles(webWasm, webDts, readFileSync(modPath, 'utf-8'));
  write(join(SUPABASE_DIR, 'pb_wasm.js'), readFileSync(join(webOut, 'pb_wasm.js'), 'utf-8'));
  write(join(SUPABASE_DIR, 'pb_wasm.d.ts'), webDts);
  write(join(SUPABASE_DIR, 'pb_wasm_bg.wasm'), webWasm);
  write(join(SUPABASE_DIR, 'pb_wasm_bg.ts'), base64);
  write(join(SUPABASE_DIR, 'mod.ts'), mod);

  if (check) {
    if (stale) { console.error(`${stale} vendored file(s) are stale; run node deploy/scripts/regen-wasm.mjs`); process.exit(1); }
    console.log('all vendored WASM glue is current');
  } else {
    console.log(stale ? `${stale} file(s) regenerated` : 'nothing to do');
  }
}

main();
